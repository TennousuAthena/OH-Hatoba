import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { createHash } from "node:crypto";

const root = fileURLToPath(new URL("../../", import.meta.url));
const require = createRequire(path.join(root, "apps/desktop/package.json"));
const ts = require("typescript");

function source(relative, read) {
  return ts.createSourceFile(relative, read(relative), ts.ScriptTarget.Latest, true);
}

/** Read the checked-in upstream bindings rather than maintain a second command map. Fail closed
 * if the generator changes shape: silently guessing parameter names could execute the wrong call. */
export function readContract(read = (relative) => fs.readFileSync(path.join(root, relative), "utf8")) {
  const file = source("apps/desktop/src/ipc/bindings.ts", read);
  const commands = {};
  let found = false;
  function visit(node) {
    if (ts.isVariableDeclaration(node) && node.name.getText(file) === "commands") {
      found = true;
      if (!node.initializer || !ts.isObjectLiteralExpression(node.initializer)) throw new Error("unsupported bindings.commands shape");
      for (const property of node.initializer.properties) {
        if (!ts.isPropertyAssignment(property) || !ts.isArrowFunction(property.initializer)) throw new Error("unsupported command declaration");
        const arrow = property.initializer;
        if (!ts.isCallExpression(arrow.body) || arrow.body.expression.getText(file) !== "__TAURI_INVOKE") throw new Error("unsupported invoke expression");
        const [name, args] = arrow.body.arguments;
        if (!name || !ts.isStringLiteral(name)) throw new Error("command name must be literal");
        const parameters = arrow.parameters.map((parameter) => {
          if (!ts.isIdentifier(parameter.name)) throw new Error("destructured command parameter");
          return parameter.name.text;
        });
        if (args && (!ts.isObjectLiteralExpression(args) || args.properties.some((p, i) => !ts.isShorthandPropertyAssignment(p) || p.name.text !== parameters[i]) || args.properties.length !== parameters.length)) {
          throw new Error(`non-positional invoke mapping: ${name.text}`);
        }
        if (!args && parameters.length) throw new Error(`missing invoke arguments: ${name.text}`);
        commands[property.name.getText(file)] = {
          command: name.text,
          parameters,
          channels: arrow.parameters.flatMap((parameter, index) => parameter.type && /^Channel</.test(parameter.type.getText(file)) ? [index] : []),
          signature: arrow.parameters.map((p) => p.getText(file)).join(", "),
          result: arrow.body.typeArguments?.map((arg) => arg.getText(file)).join(", ") ?? "unknown",
        };
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(file);
  if (!found || Object.keys(commands).length < 100) throw new Error("missing or incomplete upstream command contract");
  const ui = source("apps/desktop/src/ipc/types.ts", read);
  const events = {};
  for (const node of ui.statements) {
    if (ts.isInterfaceDeclaration(node) && node.name.text === "EventMap") {
      for (const member of node.members) {
        if (!member.name || !member.type) throw new Error("unsupported EventMap member");
        events[member.name.getText(ui).replace(/^['"]|['"]$/g, "")] = member.type.getText(ui);
      }
    }
  }
  if (!Object.keys(events).length) throw new Error("missing upstream EventMap");
  const dtos = {};
  const printer = ts.createPrinter({ removeComments: true });
  for (const node of file.statements) {
    if (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node) || ts.isEnumDeclaration(node)) {
      const declaration = printer.printNode(ts.EmitHint.Unspecified, node, file);
      dtos[node.name.text] = createHash("sha256").update(declaration).digest("hex");
    }
  }
  return { schema: 1, commands, events, dtos };
}

export function outputs() {
  const contract = readContract();
  const runtime = Object.fromEntries(Object.entries(contract.commands).map(([key, value]) => [key, { command: value.command, parameters: value.parameters, channels: value.channels }]));
  return new Map([
    ["platform/harmonyos/contracts/upstream.generated.json", `${JSON.stringify(contract, null, 2)}\n`],
    ["apps/desktop/src/ipc/harmonyos/commands.generated.ts", `// Generated by scripts/harmonyos/contracts.mjs. Do not edit.\nexport const commandContract = ${JSON.stringify(runtime, null, 2)} as const;\n`],
  ]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let drift = false;
  for (const [relative, contents] of outputs()) {
    const destination = path.join(root, relative);
    if (check) {
      if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== contents) {
        console.error(`Contract drift: ${relative}. Run node scripts/harmonyos/contracts.mjs --write and review the diff.`);
        drift = true;
      }
    } else {
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, contents);
    }
  }
  if (drift) process.exitCode = 1;
  else console.log(`HarmonyOS contract ${check ? "checked" : "generated"}: ${Object.keys(readContract().commands).length} commands`);
}

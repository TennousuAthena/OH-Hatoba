import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function separateSigning(input) {
  const profile = structuredClone(input);
  if (!profile.app?.signingConfigs?.length) throw new Error("No signing configuration was generated by DevEco");
  const local = {
    app: {
      signingConfigs: profile.app.signingConfigs,
      products: profile.app.products.filter((product) => product.signingConfig).map(({ name, signingConfig }) => ({ name, signingConfig })),
    },
  };
  delete profile.app.signingConfigs;
  for (const product of profile.app.products) delete product.signingConfig;
  return { profile, local };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] !== "capture") throw new Error("Usage: node scripts/harmonyos/local-signing.mjs capture");
  const directory = fileURLToPath(new URL("../../platform/harmonyos/", import.meta.url));
  const source = path.join(directory, "build-profile.json5");
  const destination = path.join(directory, "build-profile.local.json5");
  const { profile, local } = separateSigning(JSON.parse(fs.readFileSync(source, "utf8")));
  // Write the private copy before removing it from the shared profile. Never log its data.
  const temporary = `${destination}.tmp`;
  fs.writeFileSync(temporary, `${JSON.stringify(local, null, 2)}\n`, { mode: 0o600 });
  fs.chmodSync(temporary, 0o600);
  fs.renameSync(temporary, destination);
  fs.writeFileSync(source, `${JSON.stringify(profile, null, 2)}\n`);
  console.log("Signing material moved into ignored local configuration; shared profile is unsigned.");
}
